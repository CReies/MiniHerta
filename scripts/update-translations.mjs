import { readFile, readdir, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const runsRoot = join(root, "runs");
const outputPath = join(root, "src", "data", "spanish-item-names.ts");
const starRailResBase = "https://raw.githubusercontent.com/Mar-7th/StarRailRes/master/index_new";

// Keep these aliases aligned with scripts/download-assets.mjs. They bridge names
// used by the run datasets with the canonical StarRailRes records.
export const sourceNameAliases = {
  character: {},
  lightCone: {
    "Dance Dance Dance": "Dance! Dance! Dance!",
    "This Love Forever": "This Love, Forever",
    "To Evernights Stars": "To Evernight's Stars",
  },
};

export const sourceIdAliases = {
  character: {
    "March 7th (Preservation)": "1001",
    "March 7th (Hunt)": "1224",
    "Trailblazer (Destruction)": "8001",
    "Trailblazer: Destruction": "8001",
    "Trailblazer (Preservation)": "8003",
    "Trailblazer (Harmony)": "8005",
    "Trailblazer (Remembrance)": "8007",
    "Trailblazer (Elation)": "8009",
  },
  lightCone: {},
};

// Trailblazer records use {NICKNAME} in every language, and duplicate character
// names need their path appended to remain distinguishable in this app.
export const spanishLabelOverrides = {
  character: {
    "March 7th (Preservation)": "Siete de Marzo (Conservación)",
    "March 7th (Hunt)": "Siete de Marzo (Cacería)",
    "Trailblazer (Destruction)": "Trazacaminos (Destrucción)",
    "Trailblazer: Destruction": "Trazacaminos (Destrucción)",
    "Trailblazer (Preservation)": "Trazacaminos (Conservación)",
    "Trailblazer (Harmony)": "Trazacaminos (Armonía)",
    "Trailblazer (Remembrance)": "Trazacaminos (Reminiscencia)",
    "Trailblazer (Elation)": "Trazacaminos (Júbilo)",
  },
  lightCone: {},
};

export async function updateTranslations({
  fetcher = fetch,
  directory = runsRoot,
  destination = outputPath,
  strict = process.argv.includes("--strict"),
} = {}) {
  const [rawRuns, indexes] = await Promise.all([loadRawRuns(directory), loadSourceIndexes(fetcher)]);
  const names = collectItemNames(rawRuns);
  const result = buildTranslationMaps(names, indexes);
  const content = renderTranslationModule(result, new Date().toISOString().slice(0, 10));

  await writeFile(destination, content, "utf8");

  console.log(`Traducciones: ${result.characters.size} personajes, ${result.lightCones.size} Conos de Luz.`);
  reportUnresolved("personajes", result.unresolvedCharacters);
  reportUnresolved("Conos de Luz", result.unresolvedLightCones);

  if (strict && (result.unresolvedCharacters.length || result.unresolvedLightCones.length)) {
    process.exitCode = 1;
  }

  return result;
}

export function collectItemNames(rawRuns) {
  const characters = new Set();
  const lightCones = new Set();

  for (const rawRun of rawRuns) {
    const data = rawRun?.data || rawRun || {};
    for (const slot of [1, 2, 3, 4]) {
      addName(characters, data[`p${slot}_char`]);
      addName(lightCones, data[`p${slot}_lc`]);
    }
  }

  return { characters, lightCones };
}

export function buildTranslationMaps(names, indexes) {
  const characterResult = translateNames("character", names.characters, indexes.character);
  const lightConeResult = translateNames("lightCone", names.lightCones, indexes.lightCone);

  return {
    characters: characterResult.translations,
    lightCones: lightConeResult.translations,
    unresolvedCharacters: characterResult.unresolved,
    unresolvedLightCones: lightConeResult.unresolved,
  };
}

export function renderTranslationModule(result, synchronizedAt) {
  return `// This file is generated by scripts/update-translations.mjs.
// Source: https://github.com/Mar-7th/StarRailRes (index_new/en + index_new/es),
// joined by stable game resource ID. Last synchronized on ${synchronizedAt}.
export const spanishCharacterNames: Record<string, string> = ${renderRecord(result.characters)};

export const spanishLightConeNames: Record<string, string> = ${renderRecord(result.lightCones)};
`;
}

async function loadRawRuns(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const collections = await Promise.all(
    entries.map(async (entry) => {
      const path = join(directory, entry.name);
      if (entry.isDirectory()) return loadRawRuns(path);
      if (!entry.isFile() || !entry.name.endsWith(".json") || entry.name === "index.json") return [];
      const payload = JSON.parse(await readFile(path, "utf8"));
      return Array.isArray(payload) ? payload : payload.items || [];
    })
  );
  return collections.flat();
}

async function loadSourceIndexes(fetcher) {
  const [englishCharacters, spanishCharacters, englishLightCones, spanishLightCones] = await Promise.all([
    fetchIndex(fetcher, "en", "characters.json"),
    fetchIndex(fetcher, "es", "characters.json"),
    fetchIndex(fetcher, "en", "light_cones.json"),
    fetchIndex(fetcher, "es", "light_cones.json"),
  ]);

  return {
    character: createBilingualLookup(englishCharacters, spanishCharacters),
    lightCone: createBilingualLookup(englishLightCones, spanishLightCones),
  };
}

async function fetchIndex(fetcher, locale, filename) {
  const response = await fetcher(`${starRailResBase}/${locale}/${filename}`);
  if (!response.ok) throw new Error(`No se pudo cargar ${locale}/${filename}: HTTP ${response.status}`);
  return response.json();
}

function createBilingualLookup(english, spanish) {
  return {
    englishById: english,
    spanishById: spanish,
    englishByName: new Map(Object.values(english).map((item) => [item.name, item])),
  };
}

function translateNames(kind, names, lookup) {
  const translations = new Map();
  const unresolved = [];

  for (const name of [...names].sort((a, b) => a.localeCompare(b, "en"))) {
    const override = spanishLabelOverrides[kind][name];
    const sourceId = sourceIdAliases[kind][name];
    const sourceName = sourceNameAliases[kind][name] || name;
    const englishItem = (sourceId && lookup.englishById[sourceId]) || lookup.englishByName.get(sourceName);
    const spanishItem = englishItem && lookup.spanishById[englishItem.id];
    const label = override || spanishItem?.name;

    if (!label || label === "{NICKNAME}") {
      unresolved.push(name);
      continue;
    }

    if (label !== name) translations.set(name, label);
  }

  return { translations, unresolved };
}

function renderRecord(values) {
  if (values.size === 0) return "{}";
  const properties = [...values].map(([name, label]) => `  ${JSON.stringify(name)}: ${JSON.stringify(label)},`);
  return `{\n${properties.join("\n")}\n}`;
}

function addName(collection, value) {
  if (typeof value === "string" && value.trim()) collection.add(value.trim());
}

function reportUnresolved(label, names) {
  if (!names.length) return;
  console.warn(`Sin traducción publicada (${label}, se usará inglés):`);
  for (const name of names) console.warn(`- ${name}`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  await updateTranslations();
}
